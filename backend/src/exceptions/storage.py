"""Исключения слоя файловых хранилищ.

Хранилище отвечает за файлы, а не за бизнес-смысл операции: «не удалось
записать файл» и «нельзя менять чужую задачу» — ошибки разных слоёв.
Поэтому storage-ошибки не наследуются от `ServiceError`: вышестоящий сервис
обязан преобразовать их в свою доменную ошибку.
"""

from src.exceptions.base import ApplicationError


class StorageError(ApplicationError):
    """Базовое исключение файлового хранилища."""

    detail = "Не удалось выполнить операцию с файловым хранилищем."


class AvatarStorageError(StorageError):
    """Ошибка хранилища фотографий профиля."""

    detail = "Не удалось выполнить операцию с фотографией профиля."


class TaskAttachmentStorageError(StorageError):
    """Ошибка хранилища файлов задач."""

    detail = "Не удалось выполнить операцию с файлом задачи."
