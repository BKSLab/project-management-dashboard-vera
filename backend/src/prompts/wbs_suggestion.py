from src.prompts.base import build_system_prompt
from src.prompts.task_checklist import CHECKLIST_ANALYSIS_RULES

_WBS_SUGGESTION_INSTRUCTIONS = """Сейчас ты собираешь иерархическую структуру работ (ИСР)
по списку существующих задач проекта.

Правила разбиения:
- Разделы описывают результаты и этапы работы, а не исполнителей и не статусы.
- Правило 100%: каждая задача из входного списка попадает ровно в один раздел.
- Раздел нижнего уровня содержит от 2 до 12 задач; не создавай раздел ради одной задачи,
  если её можно отнести к соседнему по смыслу.
- Глубина — не больше 3 уровней, всего не больше 25 разделов.
- Названия — короткие существительные-результаты на языке задач проекта, до 60 символов,
  без нумерации: номера считает система.
- Разделы верхнего уровня упорядочивай по естественному ходу работ.
- Учитывай текущую структуру проекта из поля existing_structure: если она осмысленна,
  сохраняй её логику и названия разделов.

Жёсткие запреты:
- Не придумывай задачи: работай только с task_id из входного JSON.
- Не переименовывай задачи и не меняй их содержание.
- Не используй task_id, которых нет во входных данных.
- Не помещай задачу в раздел дважды.

Верни JSON:
{"nodes": [{"temp_id": "n1", "parent_temp_id": null, "title": "Аналитика",
"rationale": "почему выделен раздел"}],
"assignments": [{"task_id": 142, "node_temp_id": "n1"}],
"summary": "1-3 предложения о логике разбиения",
"skipped_task_ids": []}

temp_id — произвольные уникальные строки внутри ответа; parent_temp_id ссылается только
на temp_id из этого же ответа. В skipped_task_ids перечисли задачи, которым не нашлось
осмысленного места; их лучше оставить нераспределёнными, чем отнести наугад."""

WBS_SUGGESTION_SYSTEM_PROMPT = build_system_prompt(_WBS_SUGGESTION_INSTRUCTIONS + "\n" + CHECKLIST_ANALYSIS_RULES)
